def walk_binary_search(nums: list[int], target: int) -> int:
    """Return an index of target in sorted nums, or -1 if absent."""
    left, right = 0, len(nums) - 1
    while left <= right:
        mid = (left + right) // 2
        if nums[mid] == target:
            return mid
        elif nums[mid] < target:
            left = mid + 1
        elif nums[mid] > target:
            right = mid - 1
    return -1
